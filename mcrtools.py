# 3. MCR-ALS ANALYSIS
# =============================================================================
def runMCR(dataset, guessIndices, enforceInitialConc=True, 
           fixedSpecIndices=[ 0 ], decreasingIndices=None, increasingIndices=None,
           tol=0.001, maxdiv=20, maxIter=500):
    """
    Configures and runs the multicomponent resolution - alternating least 
    squares (MCR-ALS) algorithm from SpectroChemPy using extracted values
    from a provided NDDataset.
    """
    
    numComponents = len(guessIndices)
    
    # Extract data directly from the dataset
    rawData = dataset.data
    spectralAxis = dataset.x.data
    concAxis = dataset.y.data
    
    # Sensible defaults for constraints if not explicitly overridden
    if decreasingIndices is None:
        # at least the FIST component should be strictly decreasing
        decreasingIndices = [ 0 ]
    if increasingIndices is None:
        # at least the LAST component should be strictly increasing
        increasingIndices = [ numComponents - 1 ]

    # ---------------------------------------------------------
    # Initial guesses and dynamic labels&colors
    # ---------------------------------------------------------
    # Build initial guess spectrum (st0) by slicing the dataset
    st0List = [ rawData[ idx ] for idx in guessIndices ]
    st0 = np.vstack(st0List)

    # Dynamically map generalized labels and high-contrast colors
    componentLabels = [ "Initial species" ]
    componentColors = [ "blue" ]
    
    if numComponents > 2:
        cmap = cm.plasma
        colorVals = np.linspace(0.2, 0.8, numComponents - 2)
        for i in range(numComponents - 2):
            componentLabels.append(f"Intermediate {i+1}")
            componentColors.append(cmap(colorVals[ i ]))
            
    componentLabels.append("Final species")
    componentColors.append("red")

    # ---------------------------------------------------------
    # Configure MCR model
    # ---------------------------------------------------------
    # Change log_level to "INFO" to print out every iteration step
    mcrModel = scp.MCRALS(log_level="WARNING")

    # All concentrations and spectra should be non-negative
    mcrModel.nonnegConc = 'all'
    mcrModel.nonnegSpec = 'all'
    # All regression to be done with non-negative least squares
    mcrModel.solverConc = 'nnls'
    mcrModel.solverSpec = 'nnls'
    
    # Unimodality applied only to intermediates (if any exist)
    if numComponents > 2:
        mcrModel.unimodConc = list(range(1, numComponents - 1))
    else:
        mcrModel.unimodConc = [ ]

    # Apply spectral hard constraints
    mcrModel.hardSpec = fixedSpecIndices
    mcrModel.monoDecConc = decreasingIndices
    mcrModel.monoDecTol  = 1.05
    mcrModel.monoIncConc = increasingIndices
    mcrModel.monoIncTol  = 1.05
    
    # Python closure for custom initial concentration constraint
    def enforceInitialConcentration(cCurr):
        cArray = cCurr.data if hasattr(cCurr, 'data') else cCurr
        cArray[ 0, 0 ] = 1.0          
        cArray[ 0, 1: ] = 0.0         
        return cArray

    # Toggle the custom concentration constraint based on user argument
    if enforceInitialConc:
        mcrModel.hardConc = list(range(numComponents))
        mcrModel.getConc = enforceInitialConcentration

    # Iteration controls
    mcrModel.tol = tol              # default = 0.001
    mcrModel.maxdiv = maxdiv        # default = 20
    mcrModel.max_iter = maxIter     # default = 500

    # ---------------------------------------------------------
    # Run optimization
    # ---------------------------------------------------------
    mcrModel.fit(dataset, st0)

    # Check whether optimization has converged by returning the last line of the log
    # The first check with hasattr prevents an AttributeError in case the log attribute 
    # is actually missing. If an attribute is actually present, then checking
    # mcrModel.log prevents an IndexError if it's empty. 
    # Python's 'and' short-circuits, so the second check only runs if the first passes.
    if hasattr(mcrModel, 'log') and mcrModel.log:
        final_status = mcrModel.log.strip().split('\n')[-1]
        print(f"{final_status}")
    
    stResult = mcrModel.St
    cResult  = mcrModel.C
    dReconstructed = mcrModel.inverse_transform()

    # ---------------------------------------------------------
    # Setup plots
    # ---------------------------------------------------------
    xLabelSpec = f"{dataset.x.title} ({dataset.x.units})"
    yLabelSpec = dataset.title
    xLabelConc = f"{dataset.y.title} ({dataset.y.units})"

    # Plot 1: Resolved spectral components
    figSpec, axSpec = plt.subplots(figsize=(8, 5))
    for i in range(numComponents):
        axSpec.plot(spectralAxis, stResult.data[ i ], label=componentLabels[ i ], color=componentColors[ i ], linewidth=3)
    axSpec.set_xlabel(xLabelSpec)
    axSpec.set_ylabel(yLabelSpec)
    axSpec.set_title(f"MCR-ALS resolved spectra ({numComponents} components)")
    axSpec.legend()
    plt.tight_layout()
    plt.show()

    # Plot 2: Concentration profiles
    figConc, axes = plt.subplots(1, 2, figsize=(14, 5))
    xScales = ["linear", "log"]
    for ax, scale in zip(axes, xScales):
        for i in range(numComponents):
            ax.plot(concAxis, cResult.data[ :, i ], label=componentLabels[ i ], color=componentColors[ i ], linewidth=2, marker="o", markersize=4)
        ax.set_xscale(scale)
        ax.set_xlabel(xLabelConc)
        ax.set_ylabel("Relative fraction")
        ax.set_title(f"Concentration profiles ({scale} scale)")
        ax.legend()
    plt.tight_layout()
    plt.show()

    # Plot 3: Fit quality and fit residuals
    axMerit = mcrModel.plotmerit(
        X_hat=dReconstructed, nb_traces=5,
        exp_c="black", calc_c="darkorange", resid_c="0.4",
        exp_linestyle="-", calc_linestyle="-", resid_linestyle="-"
    )
    customLegend = [
        Line2D([ 0 ], [ 0 ], color="black", linestyle="-", label="experimental"),
        Line2D([ 0 ], [ 0 ], color="darkorange", linestyle="-", label="reconstructed"),
        Line2D([ 0 ], [ 0 ], color="0.4", linestyle="-", label="residuals")
    ]
    plt.legend(handles=customLegend, loc="best")
    plt.show()

    # Plot 4: Comparisons between first spectrum and first component, and last spectrum and last component
    figComp, axesComp = plt.subplots(1, 2, figsize=(14, 5))
    axesComp[ 0 ].plot(spectralAxis, rawData[ 0 ], label="First spectrum", color="black", linestyle="-", linewidth=2)
    axesComp[ 0 ].plot(spectralAxis, stResult.data[ 0 ], label=f"Resolved {componentLabels[ 0 ]}", color=componentColors[ 0 ], linestyle="--", linewidth=2)
    axesComp[ 0 ].set_xlabel(xLabelSpec)
    axesComp[ 0 ].set_ylabel(yLabelSpec)
    axesComp[ 0 ].set_title("Initial spectrum comparison")
    axesComp[ 0 ].legend()

    axesComp[ 1 ].plot(spectralAxis, rawData[ -1 ], label="Last spectrum", color="black", linestyle="-", linewidth=2)
    axesComp[ 1 ].plot(spectralAxis, stResult.data[ -1 ], label=f"Resolved {componentLabels[ -1 ]}", color=componentColors[ -1 ], linestyle="--", linewidth=2)
    axesComp[ 1 ].set_xlabel(xLabelSpec)
    axesComp[ 1 ].set_ylabel(yLabelSpec)
    axesComp[ 1 ].set_title("Final spectrum comparison")
    axesComp[ 1 ].legend()
    
    plt.tight_layout()
    plt.show()
    
    return mcrModel, stResult, cResult