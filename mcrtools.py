# 2. PCA RANK ANALYSIS
# =============================================================================
def runPCA(dataset, numPCAcomponents=5, plotComponents=False, normalizeProfiles=False):
    """
    Runs PCA on the NDDataset and plots the explained variance scree plot.
    We extract the explained variance data (pcaModel.ev_ratio.data) and plot 
    it manually using Matplotlib so we can set the vertical axis to logarithmic
    scaling. Text annotations are adaptively formatted and added to the base 
    of the bars using a percentage-based axes transform.
    
    If plotComponents=True, it additionally plots the PCA concentration profiles 
    (scores) and PCA spectral profiles (loadings) side-by-side using SpectroChemPy's
    native engine routed into specific Matplotlib subplots via the `ax` parameter.
    
    If normalizeProfiles=True, the PCA concentration profiles are natively min-max 
    scaled so every component stretches exactly from 0 to 1, perfectly isolating 
    the curve shapes.
    """
    pcaModel = scp.PCA(n_components=numPCAcomponents)
    pcaModel.fit(dataset)
    
    # ---------------------------------------------------------
    # 1. Explained variance scree plot
    # ---------------------------------------------------------
    evRatio = pcaModel.ev_ratio.data
    componentIndices = np.arange(1, numPCAcomponents + 1)
    
    figPca, axPca = plt.subplots(figsize=(7, 4))
    axPca.bar(componentIndices, evRatio, color="steelblue", alpha=0.7)
    axPca.set_yscale("log")
    axPca.set_xlabel("Component index")
    axPca.set_ylabel("Explained variance (%)")
    axPca.set_xticks(componentIndices)
    
    # Add adaptive percentage text to the bottom of each bar
    # Using get_xaxis_transform() locks X to data coordinates (the bar index) 
    # and Y to axes fractions (0.0 to 1.0).
    for idx, val in zip(componentIndices, evRatio):
        
        # Adaptive rounding logic
        if val >= 1.0:
            text_str = f"{val:.1f}%"    # E.g., 98.421% -> "98.4%"
        else:
            text_str = f"{val:.1g}%"    # E.g., 0.00312% -> "0.00312%" (Uses significant figures)
            
        axPca.text(
            x=idx, 
            y=0.05,  # Exactly 5% up from the bottom edge of the chart
            s=text_str, 
            color="0.3", 
            fontweight="bold",
            rotation=90, 
            ha="center",   # Center horizontally inside the bar
            va="bottom",   # Anchor the start of the text string at the Y=0.05 mark
            transform=axPca.get_xaxis_transform()
        )

    plt.tight_layout()
    plt.show()
    
    # ---------------------------------------------------------
    # 2. PCA Scores & Loadings (Native SpectroChemPy via ax)
    # ---------------------------------------------------------
    if plotComponents:
        # Extract the NDDataset objects
        pcaScores = pcaModel.transform()
        pcaSpectra = pcaModel.components
        
        # Natively normalize the scores using Min-Max: (values - min) / (max - min)
        if normalizeProfiles:
            # dim=0 explicitly calculates min and ptp across the concentrations 
            # for each independent component curve.
            min_vals = scp.min(pcaScores, dim=0)
            ptp_vals = scp.ptp(pcaScores, dim=0)
            
            # The NDDataset inherently supports this chained mathematics and broadcasts
            # the 1D arrays correctly across the curves!
            pcaScores = (pcaScores - min_vals) / ptp_vals
        
        # Create a single standard Matplotlib figure with two independent axes
        fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(12, 4))
        
        # Route the native SpectroChemPy plot for scores into the left axis (ax1)
        pcaScores.T.plot(ax=ax1)
        ax1.set_title("Concentration profiles (PCA scores)")
        
        # Route the native SpectroChemPy plot for spectra into the right axis (ax2)
        pcaSpectra.plot(ax=ax2)
        ax2.set_title("Spectral components (PCA loadings)")
        
        plt.tight_layout()
        plt.show()
        
    return pcaModel


