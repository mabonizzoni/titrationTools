"""
Generalized MCR-ALS analysis tools packaging SpectroChemPy functionality
The SpectroChemPy project is described here: https://www.spectrochempy.fr/

Travert Arnaud, Fernandez Christian (2026). SpectroChemPy, a framework for processing, 
analyzing and modeling spectroscopic data for chemistry with Python (version 0.9.4.dev74). 
Zenodo, DOI: 10.5281/zenodo.3823841 URL: https://www.spectrochempy.fr

Features:
- loadAndPackageData: Handles import of .csv and .xlsx (via pandas), generates a SpectroChemPy NDDataset object.
- runPCA: PCA component visualization.
- runMCR: Carries out the MCR-ALS analysis and plots results.
"""

import warnings
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import matplotlib.cm as cm
from matplotlib.lines import Line2D
import spectrochempy as scp

# =============================================================================
# 1. LOAD DATA AND GENERATE SpectroChemPy's NDDataset OBJECT
# =============================================================================
def loadAndPackageData(filePath, concList, titrantName, concUnit, 
                       spectralAxisName="Wavelength", spectralUnit="nm", 
                       spectraType="Absorbance", sheetName="Raw",
                       wlStart=None, wlEnd=None, 
                       concStart=None, concEnd=None):
    """
    Loads titration data from CSV or Excel file and packages it into a SpectroChemPy NDDataset object.
    Issues a warning if the file extension is not explicitly .csv, .xlsx, or .xls.
    For Excel files, it assumes by default that the raw data is placed in a tab named "Raw".
    Gracefully handles missing Excel tabs by listing available options.
    Optionally slices the data using native SpectroChemPy coordinate slicing 
    to only include the region between wlStart and wlEnd.
    """
    
    # 1. Check file extensions explicitly and warn if unrecognized
    filePathStr = str(filePath).lower()
    
    if filePathStr.endswith(('.xlsx', '.xls')):
        xls = pd.ExcelFile(filePath)
        availableTabs = xls.sheet_names
        
        if isinstance(sheetName, str) and sheetName not in availableTabs:
            raise ValueError(
                f"\nError: The requested tab '{sheetName}' does not exist in '{filePath}'. "
                f"\nAvailable tabs are: {availableTabs}"
            )
        elif isinstance(sheetName, int) and (sheetName < 0 or sheetName >= len(availableTabs)):
            raise ValueError(
                f"\nError: The requested tab index {sheetName} is out of range for '{filePath}'. "
                f"\nAvailable tabs are: {availableTabs} (indices 0 to {len(availableTabs)-1})"
            )
            
        df = pd.read_excel(xls, sheet_name=sheetName)
        rawMatrix = df.to_numpy()
        
    elif filePathStr.endswith('.csv'):
        # Standard CSV load
        # The encoding part solves a problem with CSV files generated by Excel
        rawMatrix = np.loadtxt(filePath, delimiter=",", skiprows=1, encoding="utf-8-sig")
        
    else:
        # Fallback to CSV loading but warn the user
        warnings.warn(
            f"Expected .csv or .xlsx file extension for '{filePath}'. Defaulting to CSV parsing format.",
            UserWarning
        )
        # The encoding part solves a problem with CSV files generated by Excel
        rawMatrix = np.loadtxt(filePath, delimiter=",", skiprows=1, encoding="utf-8-sig")
    
    # 2. Extract axes and transpose the spectral matrix
    spectralAxis = rawMatrix[ :, 0 ]        
    spectraData = rawMatrix[ :, 1: ].T      
    
    # 3. Validate dimensions strictly
    numSpectra = spectraData.shape[ 0 ]
    if len(concList) != numSpectra:
        raise ValueError(
            f"\nDimension mismatch: The file contains {numSpectra} spectra, "
            f"but the concentration list has {len(concList)} items."
        )
        
    # 4. Map the data type aliases to specific SpectroChemPy titles and units
    sType = str(spectraType).lower()
    if sType in [ "absorbance", "abs" ]:
        dsTitle = "Absorbance"
        dsUnits = "absorbance"
    elif sType in [ "fluorescence", "fluo", "intensity" ]:
        dsTitle = "Intensity"
        dsUnits = "intensity"
    else:
        dsTitle = str(spectraType).capitalize()
        dsUnits = sType
        
    # 5. Build SpectroChemPy coordinates
    yCoord = scp.Coord(concList, title=f"[{titrantName}]", units=concUnit)
    xCoord = scp.Coord(spectralAxis, title=spectralAxisName, units=spectralUnit)
    
    # 6. Package into NDDataset
    dataset = scp.NDDataset(
        spectraData, 
        coordset=[ yCoord, xCoord ], 
        title=dsTitle, 
        units=dsUnits 
    )

    # 7. Apply native SpectroChemPy coordinate slicing.
    # Note: SpectroChemPy requires float values to slice by physical axes
    # (e.g., wavelength) rather than matrix indices. 
    # The inline 'is not None' checks prevent a fatal TypeError (i.e., calling float(None)) 
    # in cases where the user only provides one boundary (e.g., a start but no end).
    
    # Format wavelength boundaries (x-axis / dimension 2)
    s_start = float(wlStart) if wlStart is not None else None
    s_end = float(wlEnd) if wlEnd is not None else None
    
    # Format concentration boundaries (y-axis / dimension 1)
    c_start = float(concStart) if concStart is not None else None
    c_end = float(concEnd) if concEnd is not None else None
    
    # Apply the slice to both dimensions simultaneously: [ concentrations, wavelengths ]
    if any(var is not None for var in [s_start, s_end, c_start, c_end]):
        dataset = dataset[ c_start:c_end, s_start:s_end ]
    
    return dataset


